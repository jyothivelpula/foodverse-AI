export function getCategory(categoryId) {
  return AI_LOUNGE_CATEGORIES.find((c) => c.id === categoryId) || null
}

export function getAssistant(categoryId, assistantId) {
  const category = getCategory(categoryId)
  if (!category) return null
  const assistant = category.assistants.find((a) => a.id === assistantId) || null
  if (!assistant) return null
  return { category, assistant }
}

export function chatStorageKey(categoryId, assistantId) {
  return `lounge:${categoryId}:${assistantId}`
}
